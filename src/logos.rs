//! Distro logos and detection.
//!
//! The openSUSE Geeko is converted from the openSUSE branding artwork; every
//! other logo is converted from Simple Icons 16.36.0 (CC0-1.0,
//! https://simpleicons.org). Regenerate one with:
//!
//!     tools/logo2braille.py [--bold 12] icon.svg
//!
//! (kali and linux use --bold 12). See the README for trademark notes.

use crate::theme::*;

pub struct Logo {
    /// Name accepted by `--logo`.
    pub name: &'static str,
    /// `ID` / `ID_LIKE` values from /etc/os-release that select this logo.
    pub ids: &'static [&'static str],
    /// Top and bottom colours of the vertical gradient.
    pub colors: (Rgb, Rgb),
    pub art: &'static [&'static str],
}

impl Logo {
    pub fn width(&self) -> usize {
        self.art
            .iter()
            .map(|l| l.chars().count())
            .max()
            .unwrap_or(0)
    }
}

/// Pick a logo from the contents of /etc/os-release: first by `ID`, then by
/// each `ID_LIKE` entry (so derivatives get their parent's logo), falling back
/// to Tux.
pub fn detect(os_release: &str) -> &'static Logo {
    let field = |key: &str| {
        os_release
            .lines()
            .find_map(|l| l.strip_prefix(key)?.strip_prefix('='))
            .map(|v| v.trim().trim_matches(['"', '\'']).to_string())
            .unwrap_or_default()
    };
    let id = field("ID");
    let like = field("ID_LIKE");
    std::iter::once(id.as_str())
        .chain(like.split_whitespace())
        .find_map(|id| {
            LOGOS.iter().find(|l| {
                l.ids.contains(&id) || (l.name == "opensuse" && id.starts_with("opensuse"))
            })
        })
        .unwrap_or(&LOGOS[LOGOS.len() - 1])
}

pub fn by_name(name: &str) -> Option<&'static Logo> {
    LOGOS.iter().find(|l| l.name.eq_ignore_ascii_case(name))
}

