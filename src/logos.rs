#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn detects_by_id() {
        assert_eq!(
            detect("NAME=\"Ubuntu\"\nID=ubuntu\nID_LIKE=debian\n").name,
            "ubuntu"
        );
        assert_eq!(
            detect("ID=\"opensuse-tumbleweed\"\nID_LIKE=\"opensuse suse\"\n").name,
            "opensuse"
        );
        assert_eq!(detect("ID=arch\n").name, "arch");
    }

    #[test]
    fn falls_back_to_id_like_then_tux() {
        assert_eq!(detect("ID=cachyos\nID_LIKE=arch\n").name, "arch");
        assert_eq!(
            detect("ID=nobara\nID_LIKE=\"rhel centos fedora\"\n").name,
            "rhel"
        );
        assert_eq!(detect("ID=opensuse-aeon\n").name, "opensuse");
        assert_eq!(detect("ID=somethingnew\n").name, "linux");
        assert_eq!(detect("").name, "linux");
    }

    #[test]
    fn by_name_is_case_insensitive() {
        assert_eq!(by_name("Fedora").map(|l| l.name), Some("fedora"));
        assert!(by_name("nope").is_none());
    }

    #[test]
    fn every_logo_fits_the_layout() {
        for logo in LOGOS {
            assert!(logo.width() <= 32, "{} is {} wide", logo.name, logo.width());
            assert!(
                logo.art.len() <= 16,
                "{} is {} tall",
                logo.name,
                logo.art.len()
            );
            assert!(!logo.art.is_empty(), "{} is empty", logo.name);
        }
    }

    #[test]
    fn names_are_unique() {
        for (i, a) in LOGOS.iter().enumerate() {
            assert!(
                LOGOS[i + 1..].iter().all(|b| b.name != a.name),
                "duplicate {}",
                a.name
            );
        }
    }
}
